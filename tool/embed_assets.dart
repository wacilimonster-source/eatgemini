/// 把 assets/ui 编进 Dart 源码，生成 lib/src/console/assets.g.dart。
///
/// favicon.ico 不落在磁盘：由托盘同一光栅化器（tray_glyph.dart）在构建期
/// 生成后内嵌，保证任务栏图标与托盘图标同几何同色。
///
/// 构建期会拒绝任何外部链接（桌面文档 §7 N2）。
library;

import 'dart:convert';
import 'dart:io';

import 'package:eatgemini/src/desktop/tray_glyph.dart';

Future<void> main(List<String> args) async {
  final root = Directory.current;
  final uiDir = Directory('${root.path}/assets/ui');
  if (!uiDir.existsSync()) {
    stderr.writeln('没有 assets/ui 目录');
    exit(1);
  }

  final files = uiDir
      .listSync(recursive: true)
      .whereType<File>()
      .where((f) => !f.path.endsWith('.map'))
      .toList()
    ..sort((a, b) => a.path.compareTo(b.path));

  final buffer = StringBuffer()
    ..writeln('// GENERATED by tool/embed_assets.dart — do not edit.')
    ..writeln("import 'assets.dart';")
    ..writeln()
    ..writeln('const Map<String, EmbeddedAsset> kUiAssets = {');

  var violations = 0;
  final stamp = DateTime.now().toUtc().toIso8601String();

  for (final file in files) {
    final rel = file.path
        .replaceFirst(uiDir.path, '')
        .replaceAll(String.fromCharCode(92), '/')
        .replaceFirst(RegExp(r'^/'), '');
    final bytes = file.readAsBytesSync();
    final text = _looksText(rel) ? utf8.decode(bytes, allowMalformed: true) : '';
    // xmlns / xlink 命名空间是标识符不是外链资源（内联 SVG 需要）。
    final scanned = text
        .replaceAll('http://www.w3.org/2000/svg', '')
        .replaceAll('http://www.w3.org/1999/xlink', '');
    if (scanned.contains('http://') || scanned.contains('https://')) {
      stderr.writeln('外部链接不被允许：$rel');
      violations++;
    }
    final mime = _mimeOf(rel);
    final etag = '"${bytes.length}-${_fnv(bytes)}"';
    buffer
      ..writeln("  '/ui/$rel': EmbeddedAsset(")
      ..writeln("    mime: '$mime',")
      ..writeln('    bytes: const <int>[')
      ..writeln(_wrapBytes(bytes))
      ..writeln('    ],')
      ..writeln("    etag: '$etag',")
      ..writeln('  ),');
  }

  // favicon.ico：托盘同款光栅化器生成（任务栏图标与托盘一致，精确帧不糊）。
  final favicon = buildFaviconIco();
  buffer
    ..writeln("  '/ui/favicon.ico': EmbeddedAsset(")
    ..writeln("    mime: 'image/x-icon',")
    ..writeln('    bytes: const <int>[')
    ..writeln(_wrapBytes(favicon))
    ..writeln('    ],')
    ..writeln("    etag: '\"${favicon.length}-${_fnv(favicon)}\"',")
    ..writeln('  ),');

  buffer
    ..writeln('};')
    ..writeln()
    ..writeln('/// 构建时间（仅诊断展示）。')
    ..writeln("const String kUiBuiltAt = '$stamp';");

  if (violations > 0) {
    stderr.writeln('共 $violations 个资源包含外链，构建中止');
    exit(1);
  }

  final out = File('lib/src/console/assets.g.dart');
  out.writeAsStringSync(buffer.toString(), flush: true);
  stdout.writeln('已生成 ${out.path}（${files.length} 个文件 + favicon.ico）');
}

bool _looksText(String name) =>
    name.endsWith('.html') ||
    name.endsWith('.css') ||
    name.endsWith('.js') ||
    name.endsWith('.json') ||
    name.endsWith('.svg');

String _mimeOf(String name) {
  if (name.endsWith('.html')) return 'text/html; charset=utf-8';
  if (name.endsWith('.css')) return 'text/css; charset=utf-8';
  if (name.endsWith('.js')) return 'text/javascript; charset=utf-8';
  if (name.endsWith('.svg')) return 'image/svg+xml';
  if (name.endsWith('.json')) return 'application/json; charset=utf-8';
  return 'application/octet-stream';
}

String _wrapBytes(List<int> bytes) {
  final out = StringBuffer();
  for (var i = 0; i < bytes.length; i += 24) {
    final end = (i + 24 < bytes.length) ? i + 24 : bytes.length;
    out.writeln('      ${bytes.sublist(i, end).join(',')},');
  }
  return out.toString();
}

String _fnv(List<int> bytes) {
  var hash = 0x811c9dc5;
  for (final b in bytes) {
    hash = ((hash ^ b) * 0x01000193) & 0xffffffff;
  }
  return hash.toRadixString(16);
}
